import { useEffect, useRef, useState } from "react";
import type { EditorStatus, SeleanEditor } from "../wasm/types";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
let wasmModule: Promise<any> | null = null;

/**
 * Imports and initialises the WASM package exactly once.
 *
 * The module must not be instantiated twice: a second `init()` replaces the
 * instance the first editor is running on. React StrictMode mounts effects
 * twice in development, so concurrent callers share one promise.
 */
// eslint-disable-next-line @typescript-eslint/no-explicit-any
function loadWasm(): Promise<any> {
  if (!wasmModule) {
    // Dynamic import of the WASM package generated by wasm-pack
    // (`npm run wasm:build`). The output is not checked in, so the
    // module does not exist on a clean checkout: the import is exempt
    // from type-checking and typed through `../wasm/types` instead.
    // @ts-ignore -- resolves only after the WASM build
    wasmModule = import("../wasm/pkg/selean_wasm")
      .then(async (wasm) => {
        await wasm.default();
        return wasm;
      })
      .catch((err) => {
        // Let a later mount retry instead of caching the failure.
        wasmModule = null;
        throw err;
      });
  }
  return wasmModule;
}

/**
 * Manages the lifecycle of the WASM-based SeleanEditor.
 *
 * Loads the WASM module and initializes the editor on the given canvas.
 * Keyboard shortcuts are handled by the parent component (App.tsx).
 *
 * @param canvasId - The HTML canvas element ID.
 */
export function useSeleanEditor(canvasId: string) {
  const editorRef = useRef<SeleanEditor | null>(null);
  const [status, setStatus] = useState<EditorStatus>("loading");
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    let cancelled = false;

    async function init() {
      // Check WebGPU support
      if (!navigator.gpu) {
        setStatus("unsupported");
        return;
      }

      try {
        const wasm = await loadWasm();

        if (cancelled) return;

        const editor: SeleanEditor = await wasm.SeleanEditor.create(canvasId);
        editorRef.current = editor;
        setStatus("ready");
      } catch (err) {
        if (cancelled) return;
        const message = err instanceof Error ? err.message : String(err);
        setError(message);
        setStatus("error");
      }
    }

    init();

    return () => {
      cancelled = true;
    };
  }, [canvasId]);

  return { editorRef, status, error };
}
